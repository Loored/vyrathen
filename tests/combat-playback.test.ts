import test from 'node:test';
import assert from 'node:assert/strict';
import { simulateCombat } from '../src/engine/simulator.ts';
import { PLAYER_TEAM, ENEMIES } from '../src/data/demo.ts';
import { adaptBattle, initialPlayback, transition, eventParticipants } from '../src/features/combat/playback.ts';
const battle = simulateCombat(PLAYER_TEAM, ENEMIES.patrulla.heroes, 1024);
test('replay preserves result and exact event order through jumps, restart and completion', () => {
  const before = structuredClone(battle);
  const timeline = adaptBattle(battle);
  assert.deepEqual(timeline.map(i => i.event), battle.rounds.flatMap(r => r.events));
  let state = initialPlayback(timeline);
  assert.equal(state.status, 'ready');
  state = transition(state, { type: 'play' }, timeline);
  state = transition(state, { type: 'tick' }, timeline);
  assert.equal(state.cursor, 0);
  state = transition(state, { type: 'pause' }, timeline);
  assert.deepEqual(transition(state, { type: 'tick' }, timeline), state);
  state = transition(state, { type: 'round', round: 4 }, timeline);
  assert.equal(timeline[state.cursor].round, 4);
  assert.equal(state.status, 'paused');
  state = transition(state, { type: 'restart' }, timeline);
  for (let i = 0; i < timeline.length + 20; i++) state = transition(state, { type: 'step' }, timeline);
  assert.equal(state.cursor, timeline.length - 1);
  assert.equal(state.status, 'finished');
  assert.deepEqual(transition(state, { type: 'play' }, timeline), state);
  assert.deepEqual(battle, before);
});
test('empty rounds are navigation stops, system and missing/ambiguous participants have no inferred identity', () => {
  const copy = structuredClone(battle);
  copy.rounds = [{ round: 1, events: [], attackerAlive: 5, defenderAlive: 5 }, ...copy.rounds.slice(1)];
  const timeline = adaptBattle(copy);
  const state = transition(initialPlayback(timeline), { type: 'round', round: 1 }, timeline);
  assert.equal(timeline[state.cursor].event, undefined);
  assert.equal(initialPlayback([]).status, 'empty');
  assert.deepEqual(transition(initialPlayback([]), { type: 'finish' }, []), initialPlayback([]));
  const event = { ...battle.rounds[0].events[0], actor: copy.attackers[0].name, target: copy.defenders[0].name, side: 'atacante' as const, kind: 'ko' as const };
  assert.deepEqual(eventParticipants(copy, event), { actor: copy.attackers[0].id, target: copy.defenders[0].id });
  copy.defenders[1].name = copy.defenders[0].name;
  assert.equal(eventParticipants(copy, event).target, undefined);
  assert.deepEqual(eventParticipants(copy, { ...event, side: 'sistema' }), {});
  assert.equal(eventParticipants(copy, { ...event, target: undefined }).target, undefined);
  assert.equal(eventParticipants(copy, { ...event, actor: 'Ausente' }).actor, undefined);
});
